export function detectGenderFromName(fullName: string): EmployeeGender {
  const tokens = fullName
    .toLowerCase()
    .split(/[^a-z]+/)
    .filter(Boolean);

  if (tokens.length === 0) return 'male';

  let femaleScore = 0;
  let maleScore = 0;

  tokens.forEach((token, idx) => {
    const weight = idx === 0 ? 2 : 1;
    if (FEMALE_NAME_TOKENS.has(token)) femaleScore += weight;
    if (MALE_NAME_TOKENS.has(token)) maleScore += weight;
  });

  if (femaleScore > maleScore) return 'female';
  if (maleScore > femaleScore) return 'male';

  const first = tokens[0];
  if (/(wati|ningrum|ningsih|sari|anti|yanti|ita|ina|ella|issa|isha)$/i.test(first)) {
    return 'female';
  }
  return 'male';
}

export function pickGenderAvatarUrl(gender: EmployeeGender, seedKey: string): string {
  const pool = gender === 'female' ? FEMALE_AVATAR_URLS : MALE_AVATAR_URLS;
  let hash = 0;
  for (let i = 0; i < seedKey.length; i += 1) {
    hash = (hash * 31 + seedKey.charCodeAt(i)) >>> 0;
  }
  return pool[hash % pool.length];
}

export function isBuiltInAvatarUrl(avatarUrl: string): boolean {
  return (
    (MALE_AVATAR_URLS as readonly string[]).includes(avatarUrl) ||
    (FEMALE_AVATAR_URLS as readonly string[]).includes(avatarUrl)
  );
}

export function doesAvatarMatchGender(avatarUrl: string, gender: EmployeeGender): boolean {
  if (!avatarUrl) return false;
  if (gender === 'male') {
    return (MALE_AVATAR_URLS as readonly string[]).includes(avatarUrl);
  }
  return (FEMALE_AVATAR_URLS as readonly string[]).includes(avatarUrl);
}
